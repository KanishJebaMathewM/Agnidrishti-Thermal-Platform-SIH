def get_canonical_sources(
    page: int = 1,
    limit: int = 50,
    status: Optional[str] = None,
    type_filter: Optional[str] = None,
    state: Optional[str] = None,
) -> Tuple[List[Dict[str, Any]], int]:
    """Return paginated canonical sources matching optional filters."""
    filtered = CANONICAL_SOURCES

    if status and status.lower() != "all":
        filtered = [s for s in filtered if s["status"].lower() == status.lower()]

    if type_filter and type_filter.lower() != "all":
        filtered = [s for s in filtered if s["type"].lower() == type_filter.lower()]

    if state and state.lower() != "all":
        filtered = [s for s in filtered if s["state"].lower() == state.lower()]

    total = len(filtered)
    start = (page - 1) * limit
    end = start + limit
    return filtered[start:end], total


def get_canonical_source_by_id(source_id: str) -> Optional[Dict[str, Any]]:
    """Return single source by ID."""
    for s in CANONICAL_SOURCES:
        if s["id"] == source_id:
            return s
    return None
